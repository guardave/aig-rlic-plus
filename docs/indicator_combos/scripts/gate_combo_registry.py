"""GATE-COMBO-REGISTRY: compliance gate for the indicator-combination question ledger (pure Python, no LLM).

Validates docs/indicator_combos/registry/{hypotheses,families}.yaml and keeps the generated compliance tables
(docs/indicator_combos/COMPLIANCE.md, docs/indicator_combos/registry/compliance.csv) in sync with them.

Rules (each failure is reported; exit 1 on any):
  R1  required fields present and non-empty; ids unique, D1-nn / D2-nn, direction matches the prefix
  R2  family exists in families.yaml; status in {confirmatory, exploratory, descriptive}
  R3  every baseline B1, B2a, B3, B4 is "yes: ..." or "n/a: <reason>"
  R4  pass_rule contains a number; min_events is an integer, >= 1 unless descriptive
  R5  purge_months == label_horizon_months (purge = the outcome's maximum label horizon)
  R6  len(hypotheses) == n_hypotheses; descriptive rows register no hypotheses
  R7  confirmatory: no fleet-winner members, influenced_by == [none], member tracks only vintage / market /
      snapshot_forward / label / derived, primary validation is V-C and/or V-S only, a null is named
  R8  V-D (the viewed OOS window) never appears in a primary validation
  R9  any influence (viewed_oos, full_sample_corr, d1_15) forbids confirmatory status
  R10 recession-classification rows (U4, not descriptive) name a LORO evaluation
  R11 state-dependence rows (D1-04, D1-05, D1-06, D1-17) register an interaction endpoint with min_events >= 5
  R12 rows that mention the Sahm rule carry the standard 0.50 pp trigger as a baseline or hypothesis
  R13 U3 (relative-return) rows do not use V-B (pre-1999 sector indices omit dividends)
  R14 exactly 10 ranked rows, ranks 1..10
  R15 per family: sum of n_hypotheses == n_total; confirmatory hypotheses == n_confirmatory
  R16 QUESTION_BANK.md has a heading for every id; COMPLIANCE.md and compliance.csv are up to date (--write)

Usage:  python docs/indicator_combos/scripts/gate_combo_registry.py [--write]
"""
from __future__ import annotations

import csv
import io
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REG = ROOT / "registry"
REQUIRED = ["id", "direction", "family", "title", "status", "use_case", "members", "assets", "combination",
            "label_horizon_months", "purge_months", "primary_endpoint", "pass_rule", "min_events", "event_def",
            "comparator", "baselines", "null_design", "validation", "correction", "n_hypotheses", "hypotheses",
            "uses_fleet_winners", "influenced_by", "feasibility", "priority", "rank"]
CONF_TRACKS = {"vintage", "market", "snapshot_forward", "label", "derived"}
STATE_IDS = {"D1-04", "D1-05", "D1-06", "D1-17"}
COLS = ["id", "family", "status", "use_case", "primary_endpoint", "pass_rule", "min_events", "B1", "B2a", "B3",
        "B4", "null", "validation_primary", "validation_supporting", "purge_months", "n_hypotheses",
        "n_confirmatory_hypotheses", "priority", "rank"]


def tracks(member: str) -> set[str]:
    return {t.strip() for t in member.rsplit("|", 1)[-1].split("/")}


def n_conf(q: dict) -> int:
    if q["status"] != "confirmatory":
        return 0
    return sum("exploratory" not in h for h in q["hypotheses"])


def rows(qs: list[dict]) -> list[dict]:
    out = []
    for q in qs:
        b, v = q["baselines"], q["validation"]
        out.append({"id": q["id"], "family": q["family"], "status": q["status"], "use_case": q["use_case"],
                    "primary_endpoint": " ".join(str(q["primary_endpoint"]).split()),
                    "pass_rule": " ".join(str(q["pass_rule"]).split()), "min_events": q["min_events"],
                    "B1": b["B1"], "B2a": b["B2a"], "B3": b["B3"], "B4": b["B4"], "null": q["null_design"],
                    "validation_primary": v["primary"], "validation_supporting": v["supporting"],
                    "purge_months": q["purge_months"], "n_hypotheses": q["n_hypotheses"],
                    "n_confirmatory_hypotheses": n_conf(q), "priority": q["priority"],
                    "rank": "" if q["rank"] is None else q["rank"]})
    return sorted(out, key=lambda r: (r["family"], r["id"]))


def render_csv(rs: list[dict]) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLS, lineterminator="\n")
    w.writeheader()
    w.writerows(rs)
    return buf.getvalue()


def render_md(rs: list[dict], fams: dict) -> str:
    esc = lambda x: str(x).replace("|", "/")
    L = ["# Compliance table (generated; do not edit)", "",
         "Generated by `scripts/gate_combo_registry.py --write` from `registry/hypotheses.yaml` and "
         "`registry/families.yaml`. The gate fails if this file is stale. Field meanings: QUESTION_BANK.md section 0.", ""]
    L += ["## Families", "", "| Family | Name | Hypotheses | Confirmatory | Correction (confirmatory) | Correction (exploratory) |",
          "|---|---|--:|--:|---|---|"]
    for k, f in fams.items():
        L.append(f"| {k} | {esc(f['name'])} | {f['n_total']} | {f['n_confirmatory']} | "
                 f"{esc(' '.join(str(f['correction_confirmatory']).split()))} | "
                 f"{esc(' '.join(str(f['correction_exploratory']).split()))} |")
    L += ["", f"Total: {sum(f['n_total'] for f in fams.values())} registered hypotheses, "
          f"{sum(f['n_confirmatory'] for f in fams.values())} confirmatory.", "",
          "## Questions", ""]
    for r in rs:
        L += [f"### {r['id']} · {r['family']} · {r['status']} · {r['use_case']}"
              + (f" · rank {r['rank']}" if r["rank"] != "" else ""), "",
              "| Field | Value |", "|---|---|"]
        for c in COLS[4:-1]:
            L.append(f"| {c} | {esc(r[c])} |")
        L.append("")
    return "\n".join(L)


def check(write: bool) -> list[str]:
    qs = yaml.safe_load((REG / "hypotheses.yaml").read_text())["questions"]
    fams = yaml.safe_load((REG / "families.yaml").read_text())["families"]
    err = []
    seen = set()
    for q in qs:
        i = q.get("id", "?")
        for k in REQUIRED:
            if k not in q or (q[k] in ("", None) and k != "rank") or (k in ("members",) and not q[k]):
                err.append(f"R1 {i}: missing/empty {k}")
        if not re.fullmatch(r"D[12]-\d\d", str(i)) or i in seen or str(q.get("direction")) != str(i)[1]:
            err.append(f"R1 {i}: bad or duplicate id / direction")
        seen.add(i)
        if q.get("family") not in fams:
            err.append(f"R2 {i}: unknown family {q.get('family')}")
        st = q.get("status")
        if st not in ("confirmatory", "exploratory", "descriptive"):
            err.append(f"R2 {i}: bad status {st}")
        for b in ("B1", "B2a", "B3", "B4"):
            v = str(q.get("baselines", {}).get(b, ""))
            if not (v.startswith("yes:") or (v.startswith("n/a:") and len(v) > 8)):
                err.append(f"R3 {i}: baseline {b} must be 'yes: ...' or 'n/a: <reason>'")
        if not re.search(r"\d", str(q.get("pass_rule", ""))):
            err.append(f"R4 {i}: pass_rule has no numeric threshold")
        me = q.get("min_events")
        if not isinstance(me, int) or (st != "descriptive" and me < 1):
            err.append(f"R4 {i}: min_events must be an integer (>= 1 unless descriptive)")
        if q.get("purge_months") != q.get("label_horizon_months"):
            err.append(f"R5 {i}: purge_months != label_horizon_months")
        hs = q.get("hypotheses") or []
        if len(hs) != q.get("n_hypotheses") or (st == "descriptive" and hs):
            err.append(f"R6 {i}: hypotheses list / n_hypotheses mismatch")
        val = q.get("validation", {})
        prim = str(val.get("primary", ""))
        infl = q.get("influenced_by") or []
        if st == "confirmatory":
            bad = [m for m in q["members"] if not tracks(m) <= CONF_TRACKS]
            if q.get("uses_fleet_winners") or infl != ["none"] or bad or str(q.get("null_design", "")).startswith("none") \
                    or re.search(r"V-[ABD]", prim) or not re.search(r"V-[CS]", prim):
                err.append(f"R7 {i}: confirmatory requirements violated (tracks {bad}, validation '{prim}')")
        if "V-D" in prim:
            err.append(f"R8 {i}: V-D used as primary validation")
        if set(infl) - {"none"} and st == "confirmatory":
            err.append(f"R9 {i}: influenced question cannot be confirmatory")
        if q.get("use_case") == "U4" and st != "descriptive" and "LORO" not in prim + str(val.get("supporting", "")):
            err.append(f"R10 {i}: U4 row without LORO evaluation")
        if i in STATE_IDS and ("nteraction" not in str(q.get("primary_endpoint")) or (me or 0) < 5):
            err.append(f"R11 {i}: state-dependence row needs an interaction endpoint and min_events >= 5")
        blob = " ".join(map(str, [q.get("members"), q.get("comparator"), q.get("hypotheses"), q.get("baselines")]))
        if "Sahm" in blob and "0.50" not in blob:
            err.append(f"R12 {i}: Sahm rule used without the standard 0.50 pp trigger")
        if q.get("use_case") == "U3" and "V-B" in prim + str(val.get("supporting", "")):
            err.append(f"R13 {i}: U3 row uses V-B (pre-1999 sector indices are price-only)")
    ranks = sorted(q["rank"] for q in qs if q.get("rank") is not None)
    if ranks != list(range(1, 11)):
        err.append(f"R14: ranks must be exactly 1..10, got {ranks}")
    for k, f in fams.items():
        tot = sum(q["n_hypotheses"] for q in qs if q["family"] == k)
        nc = sum(n_conf(q) for q in qs if q["family"] == k)
        if tot != f["n_total"] or nc != f["n_confirmatory"]:
            err.append(f"R15 {k}: hypotheses {tot}/{nc} vs families.yaml {f['n_total']}/{f['n_confirmatory']}")
    bank = (ROOT / "QUESTION_BANK.md").read_text() if (ROOT / "QUESTION_BANK.md").exists() else ""
    for q in qs:
        if not re.search(rf"^#+ {re.escape(q['id'])}\b", bank, re.M):
            err.append(f"R16 {q['id']}: no heading in QUESTION_BANK.md")
    rs = rows(qs)
    want = {ROOT / "COMPLIANCE.md": render_md(rs, fams) + "\n", REG / "compliance.csv": render_csv(rs)}
    for path, txt in want.items():
        if write:
            path.write_text(txt)
        elif not path.exists() or path.read_text() != txt:
            err.append(f"R16 {path.name} is stale: run with --write")
    return err


def main() -> int:
    err = check("--write" in sys.argv)
    if err:
        print("GATE-COMBO-REGISTRY FAIL")
        print("\n".join(f"  {e}" for e in err))
        return 1
    print("GATE-COMBO-REGISTRY PASS")
    return 0


if __name__ == "__main__":
    sys.exit(main())
