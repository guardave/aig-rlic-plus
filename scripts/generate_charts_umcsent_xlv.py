def chart_ccf():
    ccf_df = pd.read_csv(os.path.join(EXPLORE_DIR, "ccf.csv"))

    colors = [C_INDICATOR if sig else "#aec7e8" for sig in ccf_df["significant"]]

    fig = go.Figure()
